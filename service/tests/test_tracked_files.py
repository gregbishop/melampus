"""Tracked-files gate.

The repository is public and installs on-purpose from a checkout that lives outside
it. The installer's outputs (symlinks into that checkout, Claude Code's marketplace
path) are machine-local: tracked, they publish a home-directory layout and load
agent instructions from outside the repository on whichever machine reads them.
`.agents/on-purpose.json` records the plugin choice; the rest is regenerated by
running the installer again.

Checks against the git index rather than the working tree: no tracked symlink
resolves outside the repository, no tracked file names an absolute home-directory
path, and service/uv.lock is tracked. One check against the working tree: that
lockfile is current with service/pyproject.toml. Card #441 adds the corpus
gates: .gitignore ignores a photo corpus folder wherever it lands in the
checkout, no tracked file sits under any other fixtures folder, and every frame
in service/tests/fixtures/ is small and EXIF-free like the first one.
"""

import subprocess
from pathlib import Path

import pytest
from PIL import Image, UnidentifiedImageError

REPO = Path(__file__).resolve().parents[2]
# POSIX ERE, for git grep.
HOME_PATH = "/(Users|home)/[^/[:space:]`'\"]+/"


def _git(*args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", "-C", str(REPO), *args], check=check, capture_output=True, text=True
    )


def _tracked_symlinks():
    for entry in _git("ls-files", "-s", "-z").stdout.split("\0"):
        if not entry:
            continue
        meta, path = entry.split("\t", 1)
        mode, blob, _stage = meta.split()
        if mode == "120000":
            yield path, _git("cat-file", "-p", blob).stdout


def test_no_tracked_symlink_leaves_the_repository():
    outside = []
    for path, target in _tracked_symlinks():
        resolved = ((REPO / path).parent / target).resolve()
        if not resolved.is_relative_to(REPO):
            outside.append(f"{path} -> {target}")
    assert not outside, (
        "tracked symlinks point outside the repository (machine-local install "
        f"output; keep it untracked and rerun the installer): {outside}"
    )


def test_no_tracked_file_names_a_home_directory_path():
    hits = _git("grep", "--cached", "-I", "-n", "-E", HOME_PATH, check=False)
    assert hits.returncode == 1, (
        "tracked files name an absolute home-directory path (machine-local, and "
        f"public once pushed):\n{hits.stdout}"
    )


def test_the_lockfile_is_tracked():
    """Card #425: docs/brief.md's stack contract names service/uv.lock as the
    lockfile, and CI installs from it; a lockfile that is not in git is not one."""
    tracked = _git("ls-files", "--", "service/uv.lock").stdout.splitlines()
    assert tracked == ["service/uv.lock"], "service/uv.lock is not tracked"


def test_the_lockfile_is_current_with_pyproject():
    """A lockfile that disagrees with service/pyproject.toml pins nothing: CI's
    `uv sync --locked` would refuse it, so the suite refuses it first."""
    # --offline: a current lock verifies from the lockfile alone (no index calls,
    # cold cache included), and a drifted one must fail here, not re-resolve
    # against PyPI from inside the test suite. The timeout bounds the subprocess.
    check = subprocess.run(
        ["uv", "lock", "--check", "--offline"],
        cwd=REPO / "service",
        capture_output=True,
        text=True,
        timeout=60,
    )
    assert check.returncode == 0, check.stderr


# Card #441. Ignored: a corpus folder anywhere in the checkout. Not ignored: the
# one committed frame's folder. The rules are checked against a copy of
# .gitignore in a throwaway repository: `git check-ignore` on `fixtures/x.jpg`
# refuses a checkout where `fixtures` is a symlink to the corpus, and the
# verdict must not depend on what a given checkout has under that name.
CORPUS_PATHS = [
    # A symlink to the corpus, the way a checkout borrows one; it is not a
    # directory, so a directory-only rule (`fixtures/`) would let it through.
    "fixtures",
    "fixtures/x.jpg",
    "fixtures_full/x.jpg",
    "service/fixtures/x.jpg",
    "plugin/fixtures/x.jpg",
    "service/tests/quality/fixtures/x.jpg",
    "fixtures_full/nested/x.jpg",
]
COMMITTED_FRAME = "service/tests/fixtures/0A1A2829.jpg"


def _check_ignore(tmp_path: Path, path: str) -> subprocess.CompletedProcess[str]:
    """`git check-ignore -v` verdict for `path` under the checkout's .gitignore."""
    repo = tmp_path / "repo"
    repo.mkdir(exist_ok=True)
    (repo / ".gitignore").write_bytes((REPO / ".gitignore").read_bytes())
    subprocess.run(["git", "init", "-q"], cwd=repo, check=True)
    # 0: ignored (stdout names the source rule); 1: not ignored; other: error.
    return subprocess.run(
        ["git", "check-ignore", "-v", "--", path],
        cwd=repo,
        capture_output=True,
        text=True,
    )


@pytest.mark.parametrize("path", CORPUS_PATHS)
def test_a_corpus_folder_is_ignored_anywhere_in_the_checkout(tmp_path, path):
    verdict = _check_ignore(tmp_path, path)
    assert verdict.returncode == 0, f"{path} is committable: {verdict.stderr}"
    source = verdict.stdout.split(":", 1)[0]
    assert source == ".gitignore", verdict.stdout


def test_the_committed_frame_is_not_ignored(tmp_path):
    verdict = _check_ignore(tmp_path, COMMITTED_FRAME)
    assert verdict.returncode == 1, f"{COMMITTED_FRAME} is ignored: {verdict.stdout}"


# Card #441, Done-when 2. service/tests/fixtures/ holds one frame, downscaled
# and stripped (157 KB, no EXIF; 9351e64). A second frame is committable only
# on the same terms: under the ceiling and carrying no camera metadata, which
# the secret scanner does not read. And no tracked file may sit under any other
# fixtures folder, so a corpus cannot slip in even if the ignore rule is edited.
# Every tracked fixture that is not a text file is gated as a frame, whatever
# its suffix: an allowlist of image suffixes would let a raw (CR3, DNG), HEIC
# or BMP in unopened, and a raw carries the whole camera record.
FRAME_CEILING = 400 * 1024
TEXT_SUFFIXES = {".txt"}
FIXTURES_DIR = "service/tests/fixtures"
CORPUS_DIRS = {"fixtures", "fixtures_full"}


def _frame_problems(path: Path) -> list[str]:
    problems = []
    size = path.stat().st_size
    if size > FRAME_CEILING:
        problems.append(f"{size} bytes, over the {FRAME_CEILING} byte ceiling")
    try:
        with Image.open(path) as image:
            if image.getexif() or "exif" in image.info:
                problems.append("carries EXIF")
    except UnidentifiedImageError:
        problems.append("not an image the gate can read")
    return problems


def _is_stray_fixture(path: str) -> bool:
    """A corpus-named directory component anywhere in the path, except the
    one that is exactly service/tests/fixtures: a corpus folder nested under
    the exempt folder is still another corpus folder."""
    exempt = FIXTURES_DIR.split("/")
    parts = path.split("/")[:-1]
    return any(
        part in CORPUS_DIRS and parts[: i + 1] != exempt
        for i, part in enumerate(parts)
    )


def _stray_fixture_paths(tracked):
    """Tracked paths under a fixtures folder other than service/tests/fixtures."""
    return [path for path in tracked if path and _is_stray_fixture(path)]


def _gated_fixtures(tracked):
    """Tracked paths the frame gate opens: every fixture but a text file."""
    return [
        path
        for path in tracked
        if path and Path(path).suffix.lower() not in TEXT_SUFFIXES
    ]


def _frame(tmp_path: Path, name: str, **save) -> Path:
    path = tmp_path / name
    Image.new("RGB", (8, 8)).save(path, **save)
    return path


def test_the_committed_frame_passes_the_gate():
    assert _frame_problems(REPO / COMMITTED_FRAME) == []


def test_a_frame_over_the_ceiling_is_refused(tmp_path):
    path = tmp_path / "big.jpg"
    # Noise does not compress: 1200 x 800 at quality 100 is well over 1 MB.
    Image.effect_noise((1200, 800), 64).save(path, quality=100)
    assert any("over the" in problem for problem in _frame_problems(path))


def test_a_frame_with_exif_is_refused(tmp_path):
    exif = Image.Exif()
    exif[0x010F] = "Camera"  # Make
    assert _frame_problems(_frame(tmp_path, "tagged.jpg", exif=exif)) == [
        "carries EXIF"
    ]


def test_a_small_stripped_frame_passes(tmp_path):
    assert _frame_problems(_frame(tmp_path, "plain.jpg")) == []


def test_a_frame_the_gate_cannot_read_is_refused(tmp_path):
    # A raw file (CR3, DNG, HEIC) carries the full camera record and Pillow
    # cannot read it, so the gate cannot prove it stripped: refused, by name.
    path = tmp_path / "frame.cr3"
    path.write_bytes(bytes(range(256)) * 8)
    assert _frame_problems(path) == ["not an image the gate can read"]


def test_every_fixture_but_a_text_file_is_gated():
    # The gate selects by what a fixture is not (a text file), never by an
    # allowlist of image suffixes: a frame under any other suffix is still a
    # frame, and one the gate never opens is one it never refuses.
    tracked = [
        COMMITTED_FRAME,
        "service/tests/fixtures/download-lines.txt",
        "service/tests/fixtures/second.CR3",
        "service/tests/fixtures/second.dng",
        "service/tests/fixtures/second.bmp",
        "",
    ]
    assert _gated_fixtures(tracked) == [
        COMMITTED_FRAME,
        "service/tests/fixtures/second.CR3",
        "service/tests/fixtures/second.dng",
        "service/tests/fixtures/second.bmp",
    ]


def test_stray_fixture_paths_are_named():
    tracked = [
        COMMITTED_FRAME,
        "service/tests/fixtures/download-lines.txt",
        "fixtures_dev_labels.json",
        "service/fixtures/x.jpg",
        "plugin/fixtures/x.jpg",
        "fixtures_full/nested/x.jpg",
        "fixtures/x.jpg",
        # Under the exempt folder, but inside another corpus folder nested there.
        "service/tests/fixtures/fixtures_full/x.jpg",
        "service/tests/fixtures/fixtures/x.jpg",
        "",
    ]
    assert _stray_fixture_paths(tracked) == [
        "service/fixtures/x.jpg",
        "plugin/fixtures/x.jpg",
        "fixtures_full/nested/x.jpg",
        "fixtures/x.jpg",
        "service/tests/fixtures/fixtures_full/x.jpg",
        "service/tests/fixtures/fixtures/x.jpg",
    ]


def test_no_tracked_file_sits_under_another_fixtures_folder():
    stray = _stray_fixture_paths(_git("ls-files", "-z").stdout.split("\0"))
    assert not stray, f"a corpus is tracked outside {FIXTURES_DIR}: {stray}"


def test_every_committed_frame_is_small_and_exif_free():
    frames = _gated_fixtures(
        _git("ls-files", "-z", "--", FIXTURES_DIR).stdout.split("\0")
    )
    assert COMMITTED_FRAME in frames, "the smoke test's frame is not tracked"
    refused = {p: _frame_problems(REPO / p) for p in frames}
    refused = {p: problems for p, problems in refused.items() if problems}
    assert not refused, (
        "a committed frame is not small and stripped like the first one: "
        f"{refused}"
    )
